/**
 * 编译期内置 Profile Codegen 机制 (Ticket 02 / TC-31)
 *
 * 作用：从静态定义或 Lockfile 自动生成客户端离线首装独立信任根 profiles.generated.ts，
 * 杜绝在客户端代码中手动硬编码容易产生的字段偏移与哈希漂移。
 */
const fs = require('fs')
const path = require('path')

const REPO_ROOT = path.resolve(__dirname, '../../..')
const LOCK_FILE = path.join(
  REPO_ROOT,
  'apps/desktop/build/extraResources/configs/preset-resources.lock.json'
)
const OUTPUT_FILE = path.join(
  REPO_ROOT,
  'apps/desktop/pro/packages/shared/src/constants/profiles.generated.ts'
)

const RESOURCE_DEFINITIONS = {
  'chinese-clip': {
    resourceIdHash8: 'a42b0c8f',
    slot: 'base_embedding',
    defaultVersion: '3.0.0',
    keyEpoch: 1,
    cipherSuite: 'chacha20-poly1305',
    requiredRoles: ['visual', 'text']
  },
  'nsfw-l3': {
    resourceIdHash8: '71e9aaa6',
    slot: 'perception_nsfw',
    defaultVersion: '1.3.0',
    keyEpoch: 1,
    cipherSuite: 'chacha20-poly1305',
    requiredRoles: ['model']
  }
}

function generateCode() {
  let lockJson = null
  if (fs.existsSync(LOCK_FILE)) {
    try {
      lockJson = JSON.parse(fs.readFileSync(LOCK_FILE, 'utf8'))
    } catch {}
  }

  const profiles = {}
  for (const [resId, def] of Object.entries(RESOURCE_DEFINITIONS)) {
    let version = def.defaultVersion
    if (
      lockJson &&
      lockJson.resources &&
      lockJson.resources[resId] &&
      lockJson.resources[resId].version
    ) {
      const lockVer = lockJson.resources[resId].version
      if (/^\d+\.\d+\.\d+/.test(lockVer)) {
        version = lockVer
      }
    }
    profiles[resId] = {
      resourceIdHash8: def.resourceIdHash8,
      slot: def.slot,
      version: version,
      keyEpoch: def.keyEpoch,
      cipherSuite: def.cipherSuite,
      requiredRoles: def.requiredRoles
    }
  }

  const lines = [
    '/**',
    ' * AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.',
    ' * Generated by apps/desktop/scripts/generate-resource-profiles.js',
    ' * CI Enforcement: TC-31 (git diff --exit-code profiles.generated.ts)',
    ' */',
    '',
    'export interface ResourceProfile {',
    '  readonly resourceIdHash8: string',
    '  readonly slot: string',
    '  readonly version: string',
    '  readonly keyEpoch: number',
    "  readonly cipherSuite: 'chacha20-poly1305'",
    '  readonly requiredRoles: readonly string[]',
    '}',
    '',
    'export const BUILTIN_RESOURCE_PROFILES: Readonly<Record<string, ResourceProfile>> = {'
  ]

  const profileEntries = Object.entries(profiles)
  profileEntries.forEach(([resId, p], idx) => {
    lines.push(`  '${resId}': {`)
    lines.push(`    resourceIdHash8: '${p.resourceIdHash8}',`)
    lines.push(`    slot: '${p.slot}',`)
    lines.push(`    version: '${p.version}',`)
    lines.push(`    keyEpoch: ${p.keyEpoch},`)
    lines.push(`    cipherSuite: '${p.cipherSuite}',`)
    const rolesStr = '[' + p.requiredRoles.map(r => `'${r}'`).join(', ') + ']'
    lines.push(`    requiredRoles: ${rolesStr}`)
    lines.push(idx === profileEntries.length - 1 ? '  }' : '  },')
  })

  lines.push('} as const', '')
  lines.push(
    'export function getBuiltinProfileByHash8(idHash8: string): ResourceProfile | undefined {'
  )
  lines.push(
    '  return Object.values(BUILTIN_RESOURCE_PROFILES).find(p => p.resourceIdHash8 === idHash8)'
  )
  lines.push('}', '')
  lines.push('export function getBuiltinProfileBySlot(slot: string): ResourceProfile | undefined {')
  lines.push('  return Object.values(BUILTIN_RESOURCE_PROFILES).find(p => p.slot === slot)')
  lines.push('}', '')

  return lines.join('\n')
}

function main() {
  const isCheckMode = process.argv.includes('--check')
  const newCode = generateCode()

  if (isCheckMode) {
    if (!fs.existsSync(OUTPUT_FILE)) {
      console.error(`❌ [TC-31] ${OUTPUT_FILE} 不存在，必须运行 generate-resource-profiles.js 生成`)
      process.exit(1)
    }
    const currentCode = fs.readFileSync(OUTPUT_FILE, 'utf8')
    if (currentCode !== newCode) {
      console.error(`❌ [TC-31] ${OUTPUT_FILE} 与 Codegen 预期内容不符，存在手动漂移！`)
      process.exit(1)
    }
    console.log(`✅ [TC-31] profiles.generated.ts 校验通过，无内容漂移`)
    return
  }

  const outDir = path.dirname(OUTPUT_FILE)
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true })
  }
  fs.writeFileSync(OUTPUT_FILE, newCode, 'utf8')
  console.log(`✅ 已成功生成: ${OUTPUT_FILE}`)
}

if (require.main === module) {
  main()
}

module.exports = {
  RESOURCE_DEFINITIONS,
  generateCode,
  main
}
