/**
 * 从文件名或智能文件名中提取扩展名，无扩展名时返回空字符串
 */
export function getExtFromSmartName(name: string): string {
  if (!name) return ''
  const dot = name.lastIndexOf('.')
  return dot > 0 && dot < name.length - 1 ? name.slice(dot + 1).toLowerCase() : ''
}

