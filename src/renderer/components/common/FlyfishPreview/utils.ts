const EXTERNAL_SCROLLBAR_EXTENSIONS = new Set([
  // PowerPoint（内部无滚动条）
  'pptx',
  'pptm',
  'potx',
  'potm',
  'ppsx',
  'ppsm',
  'odp'
])

export function needsExternalScrollbar(extension: string): boolean {
  return EXTERNAL_SCROLLBAR_EXTENSIONS.has(extension.toLowerCase().replace(/^\./, ''))
}

export function isFlyfishFormat(extension: string): boolean {
  return FLYFISH_EXTENSIONS.has(extension.toLowerCase().replace(/^\./, ''))
}

export function isNativeFormat(extension: string): boolean {
  return NATIVE_EXTENSIONS.has(extension.toLowerCase().replace(/^\./, ''))
}

export function getPreviewMode(extension: string): 'flyfish' | 'native' | 'unsupported' {
  const ext = extension.toLowerCase().replace(/^\./, '')
  if (isNativeFormat(ext)) return 'native'
  if (isFlyfishFormat(ext)) return 'flyfish'
  return 'unsupported'
}
