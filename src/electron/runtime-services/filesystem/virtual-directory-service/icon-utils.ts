import Database from 'better-sqlite3'

/**
 * 获取所有已被使用的图标名称集合
 */
export function getUsedIcons(db: Database.Database): string[] {
  const rows = db
    .prepare('SELECT DISTINCT icon FROM virtual_directories WHERE icon IS NOT NULL AND icon != ?')
    .all('') as Array<{ icon: string }>
  return rows.map(r => r.icon)
}

/**
 * 挑选一个尚未被使用的唯一图标名称
 * @param candidates 候选图标名称列表
 * @param db 数据库实例
 * @returns 选中的图标名称，如果全部使用则返回第一个候选
 */
export function pickUniqueIcon(candidates: string[], db: Database.Database): string {
  if (candidates.length === 0) return 'folder'
  const used = new Set(getUsedIcons(db))
  for (const icon of candidates) {
    if (!used.has(icon)) return icon
  }
  return candidates[0]
}
